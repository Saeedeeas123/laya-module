#!/bin/bash
# Create the private GitHub repo for laya-module and push the first commit + tag.
# The token is read from the credentials note at run time and never printed.
set -u
cd /root/projects/laya-module || exit 1

TOKEN=$(grep -oE 'ghp_[A-Za-z0-9]{20,}' \
  "/sdcard/Documents/Operit_Memory/50-Config/GitHub Tokens — 2 Persistent Credentials (2026-09-25).md" | head -1)
if [ -z "$TOKEN" ]; then echo "no token found"; exit 1; fi

git init -q .
git config user.email "saeed@device.local"
git config user.name "Saeed"
TOPLEVEL=$(git rev-parse --show-toplevel)
if [ "$TOPLEVEL" != "/root/projects/laya-module" ]; then
  echo "REFUSING: git toplevel is $TOPLEVEL, not the project dir (stray .git above)"
  exit 1
fi

git add -A
git -c user.email=saeed@device.local -c user.name=Saeed commit -q -m "Laya Module v0.1.0 — the three typed primitives as an Android module

App: three tabs (choice, score, noul), a workspace per primitive, a self-test screen and the
in-app log viewer required for every app on this device.

Module (com.saeed.layamodule.laya, plain Kotlin, JVM-tested):
  LayaTokenizer  the checkpoint tokenizer packed into one asset, binary-searched
  LayaQuestion   typed question parsing, validation, option rendering
  LayaPrompts    the exact sequence and option markers the checkpoint reads
  LayaHead       logits -> typed answer + confidences
  LayaEngine     ONNX Runtime, one forward pass per state

Verified against the reference Python implementation, not against itself:
  118/118 tokenizer goldens, 70/70 prompt sequences, 14/14 decode rows on the JVM,
  and 15 recorded model answers replayed on the device by the self-test screen.
Assets and goldens are generated by tools/build_assets.py." || true

echo "=== privacy gate: creating the repo ==="
CREATE=$(curl -s -X POST https://api.github.com/user/repos \
  -H "Authorization: Bearer $TOKEN" -H "Accept: application/vnd.github+json" \
  -d '{"name":"laya-module","private":true,"description":"Laya decision engine as a reusable Android module: choice / score / noul"}')
echo "$CREATE" | python3 -c "import sys,json; d=json.load(sys.stdin); print('repo:', d.get('full_name'), 'private:', d.get('private'), 'message:', d.get('message'))"

PRIVATE=$(echo "$CREATE" | python3 -c "import sys,json; print(json.load(sys.stdin).get('private'))")
if [ "$PRIVATE" != "True" ]; then echo "REFUSING TO PUSH: repo is not private"; exit 1; fi

git remote remove origin 2>/dev/null
git remote add origin "https://$TOKEN@github.com/Saeedeeas123/laya-module.git"
git push -q -u origin main && echo "pushed main"
git tag -a v0.1.0 -m "v0.1.0 — first build, JVM-verified against the reference implementation"
git push -q origin v0.1.0 && echo "pushed tag v0.1.0"

echo "=== token must not be in .git/config ==="
if grep -q "$TOKEN" .git/config; then echo "WARNING: token is in .git/config"; else echo "clean"; fi
echo "=== remote verification ==="
curl -s "https://api.github.com/repos/Saeedeeas123/laya-module/tags" -H "Authorization: Bearer $TOKEN" \
  | python3 -c "import sys,json; [print('tag:', t['name'], t['commit']['sha'][:12]) for t in json.load(sys.stdin)]"
curl -s "https://api.github.com/repos/Saeedeeas123/laya-module" -H "Authorization: Bearer $TOKEN" \
  | python3 -c "import sys,json; d=json.load(sys.stdin); print('repo private:', d.get('private'), '| default branch:', d.get('default_branch'))"